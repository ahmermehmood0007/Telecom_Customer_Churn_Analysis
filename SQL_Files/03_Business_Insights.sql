-- Q15 Contract type with highest customers, churn and revenue

SELECT Contract,

       COUNT(*) AS total_customers,

       COUNT(
           CASE
               WHEN Churn = 'Yes' THEN 1
           END
       ) AS churn_customers,

       SUM(TotalCharges) AS total_revenue

FROM telecom_customer

GROUP BY Contract

ORDER BY total_customers DESC;



-- Q16 Most risky payment method based on churn customers

SELECT PaymentMethod,

       COUNT(
           CASE
               WHEN Churn = 'Yes' THEN 1
           END
       ) AS churn_customers

FROM telecom_customer

GROUP BY PaymentMethod

ORDER BY churn_customers DESC;



-- Q17 Customer segments for retention campaigns

SELECT

    CASE
        WHEN tenure < 12 THEN 'Low Tenure'
        WHEN tenure BETWEEN 12 AND 36 THEN 'Medium Tenure'
        ELSE 'High Tenure'
    END AS tenure_group,

    CASE
        WHEN MonthlyCharges < 50 THEN 'Low Charges'
        ELSE 'High Charges'
    END AS charges_group,

    COUNT(
        CASE
            WHEN Churn = 'Yes' THEN 1
        END
    ) AS churn_customers

FROM telecom_customer

GROUP BY tenure_group, charges_group

ORDER BY churn_customers DESC;